// ── Core translation functions ────────────────────────────────────────────────

function formatOracText(text) {
  return String(text ?? '')
    .replace(/Orac\s*Decor/gi, 'Orac Decor')
    .replace(/Oracdecor/gi, 'Orac Decor')
    .replace(/Orac\s+Decor(?=[A-ZА-ЯІЇЄҐ0-9])/g, 'Orac Decor ')
    .replace(/LED(?=[А-ЯІЇЄҐ])/g, 'LED ')
    .replace(/([а-яіїєґ])(?=Orac Decor)/gi, '$1 ')
    .replace(/([а-яіїєґ])(?=LED)/gi, '$1 ')
    .replace(/([а-яіїєґ])(?=[A-Z][0-9])/g, '$1 ')
    .replace(/([.!?])(?=[А-ЯІЇЄҐA-Z])/g, '$1 ')
    .replace(/([,:;])(?=[А-Яа-яІіЇїЄєҐґA-Z0-9])/g, '$1 ')
    .replace(/([–-])(?=[А-Яа-яІіЇїЄєҐґA-Z0-9])/g, '$1 ')
    .replace(/(?<=[А-Яа-яІіЇїЄєҐґA-Z0-9])([–-])/g, ' $1')
    .replace(/(\d)(мм|см|м²|м)/gi, '$1 $2')
    .replace(/(\d)\s*[xх]\s*(\d)/gi, '$1 x $2')
    .replace(/\s+/g, ' ')
    .trim()
}

function translateOracText(text) {
  const formatted = formatOracText(text)
  return ORAC_TEXT_REPLACEMENTS.reduce(
    (value, [pattern, replacement]) => value.replace(pattern, replacement),
    formatted
  )
    .replace(/`/g, "'")
    .replace(/\s+/g, ' ')
    .trim()
}

function translateCharacteristicValue(value) {
  let result = String(value ?? '').trim()
  for (const [src, dst] of Object.entries(CHARACTERISTIC_VALUE_UK)) {
    result = result.replace(new RegExp(src, 'gi'), dst)
  }
  return result
}

// ── Main migration ────────────────────────────────────────────────────────────

async function main() {
  const raw = await readFile(JSON_PATH, 'utf-8')
  const data = JSON.parse(raw)

  let productCount = 0

  for (const section of data.sections ?? []) {
    // Fix section title_uk
    section.title_uk = SECTION_TITLE_UK[section.title] ?? translateOracText(section.title ?? '')

    for (const product of section.products ?? []) {
      // Bake name from the Russian source (product.name) — overrides partial name_uk
      product.name_uk = translateOracText(product.name ?? '')

      // Bake description from Russian source
      product.description_uk = translateOracText(product.description ?? '')

      // Translate characteristic values in-place
      if (product.characteristics && typeof product.characteristics === 'object') {
        for (const key of Object.keys(product.characteristics)) {
          product.characteristics[key] = translateCharacteristicValue(product.characteristics[key])
        }
      }

      productCount++
    }
  }

  await writeFile(JSON_PATH, JSON.stringify(data, null, 2), 'utf-8')
  console.log(`Done: translated ${productCount} products across ${data.sections?.length ?? 0} sections.`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
